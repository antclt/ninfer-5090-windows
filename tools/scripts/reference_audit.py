#!/usr/bin/env python3
"""Print every tracked reference to a path, before that path is removed.

Why this exists
---------------
A cleanup pass deleted six `.stale` conversion reports. Two tracked documents recorded those reports
as *renamed rather than deleted, so the provenance survives* -- and the pass's guard searched for each
file's **name**. Both documents described the reports as a set, by their fate, so nothing matched, four
of the six builds now survive nowhere on this machine, and a conversion report cannot be regenerated by
inspecting an artifact. A filename search is not a reference search.

What it checks, and what it deliberately does not
------------------------------------------------
For each path given:

  * whether git tracks it -- a tracked file is never a removal candidate, and exit 2 says so;
  * every tracked file whose text names its basename, checked with a boundary so `file.log` does not
    match inside `bigfile.log`;
  * every tracked file that mentions its containing directory (reported, not counted: a mention of
    `out/` is usually not about this file);
  * every place in a tracked document where retention language sits in the same paragraph as a
    mention of the name or the directory -- kept, retained, renamed, preserved, moved to, rather than
    deleted, still wanted, archived, supersedes, disposable. This is the check that was missing.

`.gitignore` and `.dockerignore` are listed separately and do not count: a pattern list mentions a name
in order to exclude it, which is not a use. A first version of this guard counted those as references
and refused to remove five derived caches.

It is read-only and idempotent: running it twice answers the same thing.

Usage
-----
    python tools/scripts/reference_audit.py <path> [<path> ...]
    python tools/scripts/reference_audit.py --quiet <path>     # names only, no retention scan

Exit status: 0 nothing references it, 1 references found -- read them before removing, 2 it is tracked.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]

# A pattern list, not a use.
PATTERN_FILES = {".gitignore", ".dockerignore", ".gitattributes"}

# Documents where a retention decision is written down. A dated record or a rule file, not code.
DOCUMENT_SUFFIXES = (".md", ".tsv")
DOCUMENT_NAMES = {"AGENTS.md", "README.md", "NOTICE", "RELEASE_NOTES.md"}

RETENTION = re.compile(
    r"\b(kept|keep|retained|retain|renamed|rename|preserved|preserve|moved to|rather than deleted"
    r"|still wanted|archived|supersedes|superseded|disposable|not regenerable)\b",
    re.IGNORECASE,
)


def git(*args: str) -> str:
    """git, decoded explicitly: this repository's own gate fails a subprocess in text mode."""
    result = subprocess.run(["git", *args], cwd=REPO, capture_output=True, text=True,
                            encoding="utf-8", errors="replace", check=False)
    return result.stdout


def safe(text: str) -> str:
    """The console on this port is cp1252; a document holds em dashes and CJK."""
    return text.encode("ascii", "replace").decode("ascii")


def tracked_files() -> list[str]:
    return [line for line in git("ls-files").splitlines() if line.strip()]


def names_it(name: str) -> list[tuple[str, int, str]]:
    """Tracked files whose text contains `name` as a whole name, not as a substring."""
    pattern = re.compile(r"(?<![A-Za-z0-9_.\-])" + re.escape(name) + r"(?![A-Za-z0-9_.\-])")
    hits: list[tuple[str, int, str]] = []
    raw = git("grep", "-n", "--fixed-strings", name)
    for line in raw.splitlines():
        parts = line.split(":", 2)
        if len(parts) < 3:
            continue
        path, number, text = parts[0], parts[1], parts[2]
        if pattern.search(text) or pattern.search(path):
            hits.append((path, int(number), text))
    return hits


def mentions_directory(directory: str) -> list[str]:
    """Tracked files naming `directory/` as a path.

    The trailing slash and the boundary are load-bearing: a first version searched the bare directory
    name, so `out` matched inside `about` and every `docs/out/` reference, and reported 1489 files.
    """
    if not directory or directory == ".":
        return []
    pattern = re.compile(r"(?<![A-Za-z0-9_.\-])" + re.escape(directory) + r"/")
    hits: list[str] = []
    for line in git("grep", "-l", "--fixed-strings", directory + "/").splitlines():
        if line.strip() and pattern.search(line):
            hits.append(line.strip())
    return hits


def retention_lines(path: str, name: str, directory: str) -> list[tuple[int, str]]:
    """Paragraphs of a document that mention the name or directory and use retention language."""
    if not (path.endswith(DOCUMENT_SUFFIXES) or path in DOCUMENT_NAMES):
        return []
    text = (REPO / path).read_text(encoding="utf-8", errors="replace")
    needles = [needle for needle in (name, directory) if needle]
    found: list[tuple[int, str]] = []
    line_number = 1
    for paragraph in text.split("\n\n"):
        if any(needle in paragraph for needle in needles) and RETENTION.search(paragraph):
            for offset, line in enumerate(paragraph.splitlines()):
                if line.strip():
                    found.append((line_number + offset, line.strip()))
        line_number += paragraph.count("\n") + 2
    return found


# The scan is bounded, and the bound is printed: a reader has to know whether a clean answer came
# from a search of the whole tree or of its first forty files.
MAX_FILES_SCANNED = 40
MAX_LINES_PER_FILE = 4


def audit(path_text: str, quiet: bool) -> tuple[int, list[str]]:
    path = Path(path_text)
    name = path.name
    directory = path.parent.as_posix()
    if directory in (".", ""):
        directory = ""

    print(f"--- {path_text}")
    is_tracked = bool(git("ls-files", "--error-unmatch", path.as_posix()).strip())
    if is_tracked:
        # Audited anyway, then refused: a tracked removal needs its references more than an untracked
        # one does, because a commit will carry the deletion. The first version returned here and left
        # the caller to find the README lines and the header note by hand.
        print("    tracked by git: this tool's candidates are untracked files, but its references are"
              " still the ones a commit would need")

    hits = names_it(name)
    references = [(p, n, t) for p, n, t in hits if Path(p).name not in PATTERN_FILES]
    patterns = [(p, n, t) for p, n, t in hits if Path(p).name in PATTERN_FILES]

    if references:
        print(f"    named by {len(references)} tracked file(s):")
        for p, n, t in references:
            print(safe(f"      {p}:{n}: {t.strip()[:130]}"))
    else:
        print("    named by no tracked file")
    if patterns:
        print("    named only as a pattern in: "
              + ", ".join(sorted({p for p, _, _ in patterns})))

    directory_mentions = mentions_directory(directory)
    if directory_mentions:
        print(f"    its directory is named as a path by {len(directory_mentions)} file(s): "
              + ", ".join(sorted(directory_mentions)[:6]))

    retention: list[tuple[str, int, str]] = []
    from_directory = False
    if not quiet:
        # Paragraphs that *name* the file come first: they are the precise answer, and a document that
        # records a file as kept will usually name it. Directory-only mentions are the fallback and are
        # labelled, because a directory like `out/` is named in hundreds of files for other reasons --
        # a first version scanned those first and buried the paragraph that mattered under the cap.
        named = sorted({p for p, _, _ in references})
        for p in named[:MAX_FILES_SCANNED]:
            # Both needles in the precise pass: the document that records a file's fate may name it
            # in one paragraph and state the fate in another, and the paragraph stating it names the
            # directory instead. Excluding the directory here is how the first version of this missed
            # the very paragraph it exists to find.
            for number, line in retention_lines(p, name, directory + "/")[:MAX_LINES_PER_FILE]:
                retention.append((p, number, line))
        if not retention:
            for p in [q for q in sorted(directory_mentions) if q not in named][:MAX_FILES_SCANNED]:
                for number, line in retention_lines(p, "", directory + "/")[:MAX_LINES_PER_FILE]:
                    retention.append((p, number, line))
            from_directory = bool(retention)
        if retention:
            origin = " (from directory mentions, not the file's name)" if from_directory else ""
            print(f"    RETENTION LANGUAGE near a mention{origin} ({len(retention)} line(s)) -- read:")
            for p, number, line in retention:
                print(safe(f"      {p}:{number}: {line[:130]}"))

    if references or retention:
        return (2 if is_tracked else 1), [path_text]
    return (2 if is_tracked else 0), [path_text]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("paths", nargs="+", help="the file(s) you are about to remove")
    parser.add_argument("--quiet", action="store_true",
                        help="names only; skip the retention-language scan")
    args = parser.parse_args()

    status = 0
    for path in args.paths:
        code, _ = audit(path, args.quiet)
        status = max(status, code)

    print()
    if status == 2:
        print("REFUSED: at least one path is tracked by git; a removal candidate never is")
    elif status == 1:
        print("REFERENCES FOUND: read every line above before removing anything")
    else:
        print("no references: no tracked file names it and no document states a reason to keep it")
    return status


if __name__ == "__main__":
    try:
        sys.exit(main())
    except BrokenPipeError:
        # `| head` closes the pipe and Python reports the write failure as an error exit; this is the
        # documented way to leave quietly, and the audit's own answer is unaffected.
        import os

        devnull = os.open(os.devnull, os.O_WRONLY)
        os.dup2(devnull, sys.stdout.fileno())
        sys.exit(0)
